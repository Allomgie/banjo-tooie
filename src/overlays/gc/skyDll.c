// Find the sky table record for a map; returns the terminator record if there is none
int func_80800000_gcskyDll(s32 map_id)
{
    u8 *entry = &D_80800510_gcskyDll[0];
    while (*(s16 *) ((char *) entry + 0x0) != 0) {
        if (map_id == *(s16 *) ((char *) entry + 0x0)) {
            return entry;
        }
        entry += 0x24;
    }

    return entry;
}

