        state->layer[i].model = func_800B2840(state->model_asset[i]);
        func_800B2198(state->layer[i].model, bounds_min, bounds_max);
        bounds_min[0] = mlAbsF(bounds_min[0]);
        bounds_min[1] = mlAbsF(bounds_min[1]);
        bounds_min[2] = mlAbsF(bounds_min[2]);
        bounds_max[0] = mlAbsF(bounds_max[0]);
        bounds_max[1] = mlAbsF(bounds_max[1]);
        bounds_max[2] = mlAbsF(bounds_max[2]);
        for (j = 0; j < 3; j++) {
            if (extent[j] < bounds_min[j]) {
                extent[j] = bounds_min[j];
            }
            if (extent[j] < bounds_max[j]) {
                extent[j] = bounds_max[j];
            }
        }
